#!/usr/bin/env python3
"""Пункты, утверждающие отсутствие, померенное по поданным фактам.

ПЕРЕЧЕНЬ РУКОЙ НЕ ДЕРЖИТСЯ — ТРИ КРУГА ПОДРЯД ОН ОКАЗЫВАЛСЯ НЕПОЛОН. Правило
класса: пункт печатает «такого нет», а мерит отсутствие СРЕДИ ПОДАННОГО
датчиком. Файл вне перечня чтения датчика даёт ту же пустоту, что и
несуществующий, и различить их нечем — значит пункт обязан называть обе
возможности, а не одну.

Трижды класс перечисляли глазами, и трижды находился новый член: сперва
`crate-declared` и `data-model-table-migrated`, потом `ready-items-checked`,
потом `closed-unwritten`. Последнего не видел ни один грепп по `code_fact`:
он читает ПРОЕКЦИЮ `project_written_check`, которую `reproject/relations.rs`
собирает из фактов. Поэтому ищется здесь не имя факта, а весь список
проекций — он и есть то, что глаз пропускает.

Проверка не выносит приговор: она подаёт список, который человек судит. Пункт
может отбирать по факту и при этом утверждать наличие («крейт есть в
репозитории, а набором не объявлен») — такое утверждение состоятельно всегда,
и хеджировать его нечем. Решение остаётся за читающим; задача проверки — не
дать ему пропустить кандидата.
"""

import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent / "instrument" / "gate"

# Таблицы, которые `reproject/relations.rs` собирает из фактов датчика, плюс
# сама таблица фактов. Список снимается оттуда: `grep 'INSERT INTO project_'`.
ИСТОЧНИКИ = (
    "code_fact",
    "project_check_dropped",
    "project_code_dir",
    "project_code_file",
    "project_crate",
    "project_requirement_op",
    "project_task_check",
    "project_task_operation",
    "project_written_check",
    "project_written_check_dropped",
)

# Отрицательная позиция: пункт краснеет ОТ ОТСУТСТВИЯ записи, а не от наличия.
ОТРИЦАНИЕ = re.compile(r"NOT\s+EXISTS|NOT\s+IN\s*\(|IS\s+NULL|AND\s+NOT\s+\w", re.I)

# Утверждение об отсутствии в мире, а не в поданном.
УТВЕРЖДЕНИЕ = re.compile(
    r"не\s+написан|не\s+заведен|не\s+заведён|нет\s+в\s+дерев|в\s+репозитории\s+его\s+нет"
    r"|на\s+диске\s+нет|такого\s+файла\s+нет|такого\s+пути\s+нет|которого\s+нет"
    r"|отсутств|не\s+найден|не\s+существ",
    re.I,
)

# Оговорка, снимающая утверждение: ветвь говорит о ЗАМЕРЕ, а не о мире.
# «не прочитано» здесь такая же честная форма, как «среди прочитанного
# датчиком»: `ui.no-render-fields-in-protocol` говорит «модулей протокола не
# прочитано» и попадал в кандидаты, пока эту форму не знали. Ложная тревога,
# которую не снять, — та же беда, что пропуск: список, который нельзя очистить,
# перестают читать.
ОГОВОРКА = re.compile(
    r"среди\s+прочитанного\s+датчиком|не\s+снят|снят\s+БЕЗ|неизвестно|не\s+прочитан",
    re.I,
)


def главное() -> int:
    кандидаты = []
    for путь in sorted(КОРЕНЬ.rglob("*.sql")):
        if путь.name.endswith((".probe.sql", ".subject.sql", ".when.sql")):
            continue
        текст = путь.read_text(encoding="utf-8")
        # Комментарии выброшены: довод про класс не должен считаться его признаком.
        тело = "\n".join(s for s in текст.splitlines() if not s.lstrip().startswith("--"))
        читает = [и for и in ИСТОЧНИКИ if и in тело]
        if not (читает and ОТРИЦАНИЕ.search(тело)):
            continue
        # ОГОВОРКА ИЩЕТСЯ В СВОЕЙ ВЕТВИ, А НЕ ВО ВСЁМ ФАЙЛЕ. Правила здесь
        # многоветвистые, и первая ветвь почти всегда говорит «датчик не
        # подавал — неизвестно». По файлу целиком она прикрывала соседок:
        # подсадка старой редакции `ready-items-checked` прошла незамеченной,
        # хотя её вторая ветвь утверждала «не написана» без оговорки.
        for ветвь in re.split(r"\bUNION\s+ALL\b", тело, flags=re.I):
            утверждает = УТВЕРЖДЕНИЕ.search(ветвь)
            if утверждает and not ОГОВОРКА.search(ветвь):
                кандидаты.append((путь, читает, утверждает.group(0)))
                break

    if not кандидаты:
        print("Пунктов, утверждающих отсутствие без оговорки, нет.")
        return 0

    print(f"Кандидатов: {len(кандидаты)}. Каждого судит человек — см. шапку файла.\n")
    for путь, читает, слова in кандидаты:
        print(f"  {путь.relative_to(КОРЕНЬ.parent.parent)}")
        print(f"      читает: {', '.join(читает)}")
        print(f"      говорит: «{слова}»")
    return 1


if __name__ == "__main__":
    sys.exit(главное())
