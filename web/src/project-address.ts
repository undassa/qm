/**
 * Какой проект означает адрес.
 *
 * Правило одно, а применяется в двух местах: при первой загрузке и при нажатии
 * «назад». Разъехавшись, эти два места дают самую неприятную поломку — «назад»
 * никуда не ведёт, потому что адрес без параметра там значит одно, а при
 * загрузке другое.
 *
 * Адрес БЕЗ параметра значит «все проекты»: показывается сводка. Пустая строка
 * в параметре — не то же самое: это выбор, сделанный неверно, и он ведёт к
 * первому проекту, как и раньше.
 */
export interface Choice<T> {
  project: T | null;
  /** Номер из адреса, которому ничего не отвечает; пусто — всё сошлось. */
  unknown: string;
}

export function chooseProject<T extends { projectId: string }>(
  list: readonly T[],
  asked: string | null,
): Choice<T> {
  const first = list[0] ?? null;
  // АДРЕС БЕЗ ПРОЕКТА ЗНАЧИТ «ВСЕ». Прежде он значил «первый по списку», и
  // человек, открывший приложение, сразу оказывался внутри одного проекта, не
  // выбрав его. Проектов несколько, и первый вопрос — не «что у myack», а «что
  // у нас вообще»: на него отвечает сводка, а не чьи-то чужие числа.
  if (asked === null) return { project: null, unknown: "" };
  if (!asked) return { project: first, unknown: "" };
  const found = list.find((p) => p.projectId === asked);
  // Не нашли — открываем первый, но об этом говорим: молчаливая подстановка
  // показывает чужие числа под именем, которого человек не выбирал.
  return found ? { project: found, unknown: "" } : { project: first, unknown: asked };
}
