import type React from "react";

/**
 * Откуда взялись числа этой страницы.
 *
 * Практики всех пяти сущностей — трассируемость, решения, покрытие, риски,
 * словарь — жалуются на одно: артефакт ведут руками, он расходится с правдой, и
 * по нему не отличить свежее от сгнившего. Здесь расходиться нечему: второй
 * копии нет, всё считается из корпуса в момент открытия страницы.
 *
 * Сказать это обязательно. Иначе читатель поверит странице ровно настолько, на
 * сколько верил таблице, которую вёл сам, — то есть до первого расхождения.
 */
export function Provenance({
  source,
  computed,
}: {
  /** Документы корпуса, из которых собрана страница. */
  source: string;
  /** Что именно посчитано здесь, а не взято готовым. */
  computed?: string;
}): React.JSX.Element {
  return (
    <p className="prov-foot">
      <b>Ничего из этого не введено руками.</b> Страница собрана из <code>{source}</code> в момент открытия
      {computed ? <>; {computed} посчитано здесь же, а не хранится</> : null}. Расходиться с корпусом ей нечем — второй
      копии не существует.
    </p>
  );
}
