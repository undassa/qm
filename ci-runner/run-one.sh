#!/usr/bin/env bash
# Один раннер на одну работу. Хост чеканит короткоживущий токен регистрации и
# отдаёт его контейнеру; личный токен остаётся на хосте.
#
# Тома у контейнера нет вовсе: именованный том создаётся докером от root, и
# раннер, живущий под своим пользователем, в него не пишет — работа падала на
# втором шаге, не сказав чем. Дерево живёт в самом контейнере и умирает с ним,
# что для одноразового раннера и нужно.
#
# Контейнер без монтирований хоста НАРОЧНО: он исполняет содержимое воркфлоу
# как обычные команды, а на этой машине рядом стоят `mh-web`, общая база и
# чекауты наборов. Рабочее дерево живёт на своём томе и умирает с контейнером.
set -euo pipefail

# Довод — `репозиторий` либо `репозиторий:номер`. Номер нужен затем, чтобы на
# одном репозитории работало несколько раннеров: раннер берёт ОДНУ работу за
# раз, и шесть работ прогона шли друг за другом. Двоеточия в имени репозитория
# не бывает, поэтому разрез по последнему однозначен.
ARG="${1:?укажи репозиторий, например tot-space/tot-ade или tot-space/tot-ade:2}"
REPO="${ARG%:*}"
N="${ARG##*:}"
[ "$N" = "$ARG" ] && N=1
slug="${REPO//\//-}-${N}"

token=$(gh api -X POST "repos/${REPO}/actions/runners/registration-token" --jq .token)

# ДОЛЯ CPU УМНОЖАЕТСЯ НА ЧИСЛО РАННЕРОВ, А ЯДЕР ОТ ЭТОГО НЕ ПРИБАВЛЯЕТСЯ.
# `--cpus` — потолок, а не резерв: пятеро по четыре просили двадцать на
# шестнадцати, нагрузка стояла 22, и postgres ВНУТРИ контейнера переставал
# отвечать на подключение посреди работы. Выглядело это как четыре упавших
# теста про базу — то есть как дефект правки, которой там не было; трижды за
# день по этому следу искали ошибку в коде. Пять по три укладываются в
# шестнадцать. Меняя число здесь, посчитай его заново вместе с числом
# запущенных `ci-runner@`.
exec docker run --rm \
  --name "ci-runner-${slug}" \
  --hostname "ci-${slug}" \
  --cpus 3 --memory 8g \
  -e REPO="${REPO}" \
  -e RUNNER_TOKEN="${token}" \
  -e RUNNER_NAME="ci-${slug}" \
  -e RUNNER_LABELS="self-hosted,linux,x64" \
  ci-runner:local
