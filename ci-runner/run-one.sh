#!/usr/bin/env bash
# Один раннер на одну работу. Хост чеканит короткоживущий токен регистрации и
# отдаёт его контейнеру; личный токен остаётся на хосте.
#
# Тома у контейнера нет вовсе: именованный том создаётся докером от root, и
# раннер, живущий под своим пользователем, в него не пишет — работа падала на
# втором шаге, не сказав чем. Дерево живёт в самом контейнере и умирает с ним,
# что для одноразового раннера и нужно.
#
# Контейнер без монтирований хоста НАРОЧНО: он исполняет содержимое воркфлоу
# как обычные команды, а на этой машине рядом стоят `mh-web`, общая база и
# чекауты наборов. Рабочее дерево живёт на своём томе и умирает с контейнером.
set -euo pipefail

# Довод — `репозиторий` либо `репозиторий:номер`. Номер нужен затем, чтобы на
# одном репозитории работало несколько раннеров: раннер берёт ОДНУ работу за
# раз, и шесть работ прогона шли друг за другом. Двоеточия в имени репозитория
# не бывает, поэтому разрез по последнему однозначен.
ARG="${1:?укажи репозиторий, например tot-space/tot-ade или tot-space/tot-ade:2}"
REPO="${ARG%:*}"
N="${ARG##*:}"
[ "$N" = "$ARG" ] && N=1
slug="${REPO//\//-}-${N}"

# РАБОТА, КОТОРОЙ НЕ ХВАТИТ ДИСКА, ПАДАЕТ ВИДОМ ДЕФЕКТА КОДА. Замерено дважды
# 2026-09-26: `ld terminated with signal 7 [Bus error]` и «couldn't create a temp
# dir: No space left on device» — в крейте, которого ветка не трогала вовсе.
# Держатель ревью прочёл цвет прогона и выдал диагноз про втяг ствола, не открыв
# лог; час работы двух сессий ушёл на класс, которого не было.
#
# СПРАШИВАЕТСЯ ТОЛЬКО СВОБОДНОЕ МЕСТО, И ЭТО РЕЗУЛЬТАТ ДВУХ НЕУДАЧ. Первая
# редакция стояла в `entrypoint.sh` и пропускала ровно тот случай, ради которого
# написана. Вторая умножала порог на число работающих братьев — и отказывала на
# пустом диске: замерено на живой машине, четверо работающих при 31 ГБ свободных
# давали «нужно 75», хотя их записи вместе весили 9.2 ГБ. Причина в том, что
# «сколько диска запросит сосед» из `docker ps` не выводится: раннер `--ephemeral`
# бо́льшую часть времени просто стоит зарегистрированным и ждёт работы, а уже
# израсходованное им место в `free` УЖЕ вычтено — множитель считал его второй раз.
# В установившемся состоянии такой предикат пускал бы не больше двух раннеров из
# семи и делал это молча.
#
# Одновременность ограничивается не здесь, а числом включённых юнитов
# `ci-runner@`: это выбор под размер диска, и делается он один раз руками, а не
# пересчитывается каждым раннером по данным, которых у него нет. Число работающих
# печатается рядом — как сведение для читающего лог, не как множитель.
#
# Порог выбран, а не выведен. Наблюдения за вечер: записи живых контейнеров шли
# от 0.4 до 8.5 ГБ, причём бо́льшая часть выборок укладывалась в 4, а сборочные
# деревья на хосте доходят до 19 ГБ. 15 выше обычного и ниже худшего; если работа
# начнёт падать при зелёной проверке, число мало, и поднимать его надо по замеру.
#
# Вид работы на момент проверки НЕ ИЗВЕСТЕН НИКОМУ: замер идёт до регистрации, а
# что пришлёт GitHub — решается позже. Поэтому порог один на все шесть работ, хотя
# `docs` и `deps` прошли бы и на пяти гигабайтах. Различить их здесь нечем, и
# городить пороги по видам работ бесполезно.
#
# И замер отстоит от применения: раннер регистрируется, стоит и ждёт работы, а
# диск в это окно проседает от соседей и от самого харнеса. Полностью это
# закрывает только шаг в начале самого воркфлоу — единственное место, где замер
# совпадает с моментом использования. Он живёт в чужом репозитории и множится по
# каждому набору; здесь выбрано одно место на все наборы, и это размен.
#
# Место здесь, а не в `entrypoint.sh`: отказ не тратит чеканку токена GitHub, и
# правка не требует пересборки образа.
#
# СОН ПЕРЕД ВЫХОДОМ ОБЯЗАТЕЛЕН: юнит несёт `Restart=always` и `RestartSec=5`, а
# нехватка диска держится часами. Без сна семь юнитов крутили бы отказ каждые
# ~6 секунд. Ограничитель частоты юнита (`StartLimitBurst`) здесь НЕ страхует:
# при умолчании в 300 секунд один старт на окно, и сработать он не может. У самой
# ручки есть обрыв — значение ниже ~6 секунд укладывает пять стартов в минуту, и
# юнит уходит в `failed` до руки человека, а не крутится дальше.
#
# `|| true` у обоих присваиваний не лень: при `set -e -o pipefail` падение `df`
# или демона докера роняет САМО присваивание, и скрипт умирает не напечатав ни
# строки — то есть проверка, заведённая ради имени причины, отняла бы имя у себя.
: "${CI_MIN_FREE_GB:=15}"
: "${CI_FULL_DISK_SLEEP_S:=300}"
# Куда пишет докер, объявлено у демона: литерал здесь был бы второй копией этого
# факта, и при переносе `data-root` он разошёлся бы молча — проверка мерила бы
# чужую файловую систему и пропускала при полной настоящей.
docker_root=$(docker info --format '{{.DockerRootDir}}' 2>/dev/null) || docker_root=/opt/docker
free_gb=$(df --output=avail -BG "$docker_root" 2>/dev/null | tail -1 | tr -dc '0-9' || true)
busy=$(docker ps --filter name=ci-runner- --quiet 2>/dev/null | wc -l) || busy="не спрошено"
if [ -z "$free_gb" ]; then
  # Непомеренное — не «мало»: отказ по несостоявшемуся замеру остановил бы
  # очередь из-за сломанной проверки. Говорим вслух и работаем дальше.
  echo "диск: померить не удалось, порог не проверен" >&2
elif [ "$free_gb" -lt "$CI_MIN_FREE_GB" ]; then
  echo "диск: свободно ${free_gb} ГБ при пороге ${CI_MIN_FREE_GB} ГБ," \
       "работает раннеров ${busy}. Работа не начата;" \
       "сон ${CI_FULL_DISK_SLEEP_S} с, потом ещё замер." >&2
  sleep "$CI_FULL_DISK_SLEEP_S"
  exit 1
else
  echo "диск: свободно ${free_gb} ГБ при пороге ${CI_MIN_FREE_GB} ГБ, работает раннеров ${busy}"
fi

token=$(gh api -X POST "repos/${REPO}/actions/runners/registration-token" --jq .token)

# ДОЛЯ CPU УМНОЖАЕТСЯ НА ЧИСЛО РАННЕРОВ, А ЯДЕР ОТ ЭТОГО НЕ ПРИБАВЛЯЕТСЯ:
# пятеро по четыре просили двадцать на шестнадцати. Пять по три укладываются.
#
# Но само по себе это НЕ лечит голод, и первая редакция этой правки объявила
# его вылеченным напрасно: `--cpus` ставит квоту cgroup и не трогает привязку,
# так что `nproc` внутри отвечает 16 при любом значении. Настоящее согласие
# числа потоков с квотой живёт в `entrypoint.sh`; здесь — только внешняя сумма.
# Меняя число, посчитай его вместе с числом запущенных `ci-runner@` И с тем,
# что делает на машине хозяин: он тоже собирает.
#
# 2026-09-24: было трое по три на `tot-ade` плюс двое на `mh` — пятнадцать ядер
# из шестнадцати. Стало семеро по два: четырнадцать, и хозяину остаётся два.
# Прогон набора — шесть работ, а слотов было три, то есть один прогон шёл в две
# волны, а очередь из пяти — в десять. Пять слотов на `tot-ade` кроют прогон за
# две волны при любой очереди.
#
# ПАМЯТЬ СНИЖЕНА ВМЕСТЕ С ЯДРАМИ, И ЭТО НЕ ОСТОРОЖНОСТЬ, А АРИФМЕТИКА: семеро
# по восемь просили бы пятьдесят шесть из шестидесяти двух, и сборка хозяина
# рядом клала бы машину — так уже было, oom-killer снял рабочую сессию. Расход
# памяти идёт за числом потоков, а их теперь два, а не три.
# ПРОФИЛЬ SECCOMP — ДОКЕРОВСКИЙ ПЛЮС КОЛЬЦО. Профиль по умолчанию отвечает на
# `io_uring_setup` EPERM, и проверка, меряющая наш фильтр сокетов против кольца
# (`m5_t344`, `V5-T360`), читает «этот хозяин не меряет» и краснеет на каждом
# прогоне здесь. `seccomp.json` рядом — профиль moby (github.com/moby/profiles)
# плюс три вызова io_uring; владелец одобрил 2026-10-06.
exec docker run --rm \
  --name "ci-runner-${slug}" \
  --hostname "ci-${slug}" \
  --cpus 2 --memory 6g \
  --security-opt "seccomp=$(dirname "$(readlink -f "$0")")/seccomp.json" \
  -e REPO="${REPO}" \
  -e RUNNER_TOKEN="${token}" \
  -e RUNNER_NAME="ci-${slug}" \
  -e RUNNER_LABELS="self-hosted,linux,x64" \
  ci-runner:local
