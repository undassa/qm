-- ПРИЧИНУ НАЗЫВАЕТ `fact_gap`, А НЕ ЭТОТ ЗАПРОС. Несвежесть бывает пяти родов:
-- не подавал ни разу, снят с грязного дерева, снят без коммита, срок не
-- объявлен, подавал и протух по сроку. Здесь стояло двое из пяти, и три
-- остальных выходили под ярлыком «последняя подача старше объявленного срока»
-- — то есть под чужой причиной. Набор `tot-ade` потратил на такой диагноз
-- целый заход: датчики отвечали, отметка стояла четырьмя часами ранее при
-- сроке в неделю, а несвежими они были оттого, что сняты с грязного дерева.
--
-- СРОК СУДИТСЯ ТАМ, ГДЕ ЕГО МОЖНО ОСВЕЖИТЬ; ВСЁ ОСТАЛЬНОЕ — У КАЖДОГО ДАТЧИКА.
-- 01.10 выдача tot-ade встала на `onboarding-run`: это запись ручного проигрыша
-- онбординга, поданная 23.09 чисто и с коммитом, со сроком в неделю. Проиграть
-- онбординг сегодня нечем (бинаря и поверхности в дереве ещё нет), и работа
-- владельца ступени (`godzy-update`, то есть `mh sense`) такой факт не освежает:
-- `mh sense` ходит только по образцам съёма (`project_sensor_spec`). Находка
-- держала бы очередь, пока не появится продукт.
--
-- Поэтому истечение срока судится лишь у датчика с образцом — его освежает
-- `mh sense`. «Не подавал ни разу», «снят с грязного дерева» и «без коммита»
-- судятся у ВСЕХ объявленных: датчик, объявленный без образца, не подаёт
-- никогда, и это самая частая ошибка набора — её ступень обязана называть.
-- Срок ручного факта судит пункт, который его читает (`G5 · onboarding-run`
-- сам спрашивает `fact_fresh`).
WITH последняя AS (
  SELECT DISTINCT ON (fp.fact) fp.fact, fp.dirty, fp.commit_sha
    FROM fact_push fp WHERE fp.project_id = $1
   ORDER BY fp.fact, fp.at DESC)
SELECT s.fact || ' — ' || fact_gap(s.project_id, s.fact) AS detail
  FROM sensor s
  LEFT JOIN последняя п ON п.fact = s.fact
 WHERE s.project_id = $1 AND NOT fact_fresh(s.project_id, s.fact)
   AND (EXISTS (SELECT 1 FROM project_sensor_spec p
                 WHERE p.project_id = s.project_id AND p.fact = s.fact)
        OR п.fact IS NULL OR п.dirty OR п.commit_sha = '')
 ORDER BY 1
