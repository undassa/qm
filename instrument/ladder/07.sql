-- ПРИЧИНУ НАЗЫВАЕТ `fact_gap`, А НЕ ЭТОТ ЗАПРОС. Несвежесть бывает нескольких
-- родов: не подавал ни разу, снят с грязного дерева, снят без коммита, снят не с
-- вершины ствола, срок не объявлен, подавал и протух по сроку. Набор `tot-ade`
-- однажды потратил заход на чужую причину: датчики отвечали, а несвежими они
-- были оттого, что сняты с грязного дерева.
--
-- ДВА РОДА ФАКТОВ, И СУДЯТСЯ ОНИ ПО-РАЗНОМУ (заявка 18, решение владельца
-- 2026-09-17).
--
-- Род С ОБРАЗЦОМ СЪЁМА (`project_sensor_spec`) — факт о репозитории. Его снимает
-- харнес со ствола сам после слияния, и свеж он вершиной ствола, а не сроком;
-- объявлять срок ему не нужно. Несвежий род с образцом значит, что съём не
-- подал его на последней вершине: образец не находит, что читать, или датчик
-- падает. Чинится образец — работа набора, — а не ручная подача: её сервер
-- отказывает.
--
-- Род БЕЗ образца — наблюдение руками (`onboarding-run`: ручной проигрыш
-- онбординга). Харнесу снять его нечем, и истечение его срока судит пункт,
-- который его читает (`G5 · onboarding-run` сам спрашивает `fact_fresh`): 01.10
-- выдача tot-ade встала на таком факте, освежить который было нечем. Здесь у
-- объявленного рода без образца судится только «не подавал ни разу», «снят с
-- грязного дерева» и «без коммита»: датчик, объявленный без образца и ни разу
-- не подавший, — самая частая ошибка набора, и её ступень обязана называть.
WITH последняя AS (
  SELECT DISTINCT ON (fp.fact) fp.fact, fp.dirty, fp.commit_sha
    FROM fact_push fp WHERE fp.project_id = $1
   ORDER BY fp.fact, fp.at DESC),
роды AS (
  SELECT fact, true AS снимается FROM project_sensor_spec WHERE project_id = $1
  UNION
  SELECT s.fact, false FROM sensor s
   WHERE s.project_id = $1
     AND NOT EXISTS (SELECT 1 FROM project_sensor_spec p
                      WHERE p.project_id = s.project_id AND p.fact = s.fact))
SELECT р.fact || ' — ' || fact_gap($1, р.fact) AS detail
  FROM роды р
  LEFT JOIN последняя п ON п.fact = р.fact
 WHERE NOT fact_fresh($1, р.fact)
   AND (р.снимается OR п.fact IS NULL OR п.dirty OR п.commit_sha = '')
 ORDER BY 1
