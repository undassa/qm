-- ПРОБА САЖАЕТ СВОЙ ПРЕДИКАТ, А НЕ ЗАНИМАЕТ ЕГО У НАБОРА. Правило различает
-- «каталога нет» и «обход туда не дошёл» по верхнему каталогу, а верхи берёт
-- из `project_code_dir`. Первая редакция этой пробы зашивала `crates` и молча
-- зависела от того, что у набора такой верх есть: у набора без крейтов обе
-- строки ушли бы в одну ветвь, и вторая осталась бы непроверенной ни разу.
-- Поэтому верх подсаживается здесь же, одним запросом — иначе проба судила бы
-- о правиле по данным, которых сама не клала.
--
-- ДВЕ СТРОКИ, И ПОТОЛОК НАЗВАН ЧЕСТНО. `нет-такого-верха-пробы` в
-- `project_code_dir` не значится — это ветвь «обход не дошёл»; `верх-пробы`
-- значится, а самого каталога под ним нет — это ветвь «каталога нет».
--
-- Но РАЗЛИЧИТЬ ветви самотест не умеет, и обещать этого нельзя: приговор —
-- «ответ пункта изменился» (`became != was`), и одной строки для него довольно.
-- Вырежи любую ветвь — вторая строка всё равно даст находку, ответ изменится,
-- пункт будет объявлен живым. Две строки дают ровно то, что дают: обе ветви
-- ИСПОЛНЯЮТСЯ на подсадке, то есть падение или пустой результат в любой из них
-- виден. Разделить приговор можно двумя пунктами гейта или усилением самотеста;
-- ни того ни другого здесь не сделано.
WITH к AS (
  INSERT INTO project_code_dir (project_id, dir) VALUES ($1, 'верх-пробы') RETURNING project_id)
INSERT INTO project_task_tree_leaf(project_id, task_id, ord, dir, leaf, is_path, exempt, target_dir, forward_declared)
SELECT $1, min(t.id), 9998, 'проба', 'нет-такого-верха-пробы/каталог', true, false, 'нет-такого-верха-пробы/каталог', false
  FROM project_plan_tasks t, к WHERE t.project_id=$1
UNION ALL
SELECT $1, min(t.id), 9997, 'проба', 'верх-пробы/нет-такого-каталога/файл', true, false, 'верх-пробы/нет-такого-каталога', false
  FROM project_plan_tasks t, к WHERE t.project_id=$1
