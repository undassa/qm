-- «датчик туда не дошёл»: различить их нечем, и подсаживать вторую ветвь не во
-- что. Потолок назван честно: приговор самотеста — «ответ пункта изменился», и
-- одной строки для него довольно.
--
-- `leaf` ГОЛЫЙ, А ПУТЬ ЛЕЖИТ В `path` — так, как их кладёт `tree_leaf.rs`.
-- Проба, у которой путь был написан в `leaf`, щупала лучший случай: у `myack`
-- 383 листа из 419 несут в `leaf` голое имя, и правило, печатавшее `leaf`,
-- дало бы на три разных каталога `M1-T2 — mod.rs` три раза слово в слово.
-- Сослагательное здесь нарочно: все три каталога сейчас на месте, строк этих
-- в живом наборе нет, и форма измерена подсадкой, а не наблюдением.
--
-- ПОТОЛОК И У ЭТОГО ВОПРОСА. Приговор самотеста — «ответ пункта изменился», и
-- какую колонку правило печатает, он не видит: вернуть `path` обратно в `leaf`
-- можно завтра, и проба, гейт и CI останутся зелёными. Колонку держит
-- читающий, а не прибор.
