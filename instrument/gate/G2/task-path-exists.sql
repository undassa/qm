-- версий её не держат (решение владельца 2026-10-07). Без открытой версии — весь набор.
-- ЧТО ДАТЧИК ПРОЧЁЛ, А НЕ ЧТО ЛЕЖИТ В ДЕРЕВЕ. Каталоги правило берёт из
-- поданных фактов, поэтому путь, до которого датчик не дошёл, даёт ту же
-- пустоту, что и несуществующий, — а правило утверждало второе.
--
-- Что это стоило: адрес `.config/nextest.toml` лежал в дереве `tot-ade`, набор
-- ссылался на него прозой в шести местах, а находка звала каталог
-- несуществующим — `.config/**` не было в перечне чтения датчика `repo-file`.
-- Исполнитель час искал ошибку в дереве, завёл обход и написал заявку с
-- неверной причиной («пропускают каталоги с точки»): дотовых каталогов в
-- перечне было четыре, пятого не было.
--
-- РАЗВИЛКУ НАЗВАТЬ НЕЧЕМ, И ПРАВИЛО ЕЁ НЕ НАЗЫВАЕТ. Три редакции пытались
-- различить «каталога нет» и «датчик туда не дошёл»: по глобам
-- `project_sensor_spec.reads`, по каталогам `project_code_dir`, по верхнему
-- отрезку имени прочитанного факта. Все три врали, потому что ни одна не
-- описывает обход, а замена знает лишь часть его.
--
-- Что зазор не умозрительный, видно замером до mh#111: у `myack` датчик
-- `repo-file` читал восемь ветвей (`backend/**/*`, `frontend/**/*`, …) и ни
-- одной корневой записи — среди 415 поданных им файлов корневых было ноль. Лежащий в
-- дереве `README.md` для правила отсутствовал, и никакой глоб этого не сказал
-- бы: правило видит только имена, которые датчик подал.
--
-- Причина общая: досягаемость датчика (`client.rs::reach`) не выражается ни
-- глобом, ни каталогом, ни верхом. Сам `repo-file` с заявки 111 читает всё,
-- что отслеживает git, и объявленный перечень ему не указ; но `code-file`
-- идёт по образцам набора, а незакоммиченного файла не видит ни один из двух.
-- Правило, которое чинит ложное утверждение, не вправе заводить своё
-- описание обхода.
--
-- Поэтому сказано ровно измеренное, а обе возможности названы читателю. Одно
-- сообщение короче трёх редакций разветвления и не врёт ни на одном входе.
SELECT 'датчик файлов дерева «repo-file» ' || fact_gap($1, 'repo-file')
       || ': есть ли каталоги задач — неизвестно, и это не зелёное' AS detail
 WHERE NOT (fact_fresh($1, 'repo-file') OR fact_fresh($1, 'code-file'))
   AND EXISTS (SELECT 1 FROM project_task_tree_leaf l
                WHERE l.project_id = $1 AND l.is_path AND NOT l.exempt)
UNION ALL
SELECT l.task_id || ' — ' || l.path || ': среди прочитанного датчиком такого пути нет. '
       || 'Каталога нет в дереве либо он не закоммичен; '
       || 'если свеж только `code-file`, он ещё мог лечь вне его образцов — покажет `sensor-specs`' AS detail
  FROM project_task_tree_leaf l
 WHERE l.project_id = $1 AND (fact_fresh($1, 'repo-file') OR fact_fresh($1, 'code-file'))
   AND l.is_path AND NOT l.exempt AND NOT l.forward_declared
   AND l.target_dir <> '' AND l.op <> '+'
   AND NOT EXISTS (SELECT 1 FROM task_scope sc WHERE sc.project_id = l.project_id AND sc.task_id = l.task_id AND sc.scope IN ('next','later'))
   AND NOT EXISTS (SELECT 1 FROM project_code_dir d
                    WHERE d.project_id = $1 AND d.dir = l.target_dir)
 ORDER BY 1
