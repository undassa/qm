WITH прогон AS (
  SELECT max(at) AS at FROM test_run WHERE project_id = $1 AND NOT dirty),
-- ПЕРЕАДРЕСОВАННЫЙ ПУНКТ НЕ ОБЕЩАЕТ, А ОТКАЗЫВАЕТ.
--
-- «Сценарий `TC-SANDBOX-02` здесь не закрывается: совершённое необратимое
-- перечисляет в `receipt` `M3-T13`» — это не обещание доказать сценарий, а
-- отказ с адресом. Правило видело в строке имя сценария и требовало
-- доказательства; предмет строки — ровно противоположное. Пять находок из
-- одиннадцати были такими.
--
-- Слово отказа объявлено набором (`word.elsewhere`), а не угадано здесь:
-- «здесь не закрыва», «пройденными не отмеча». Глагол «закрывает» в роль не
-- положен намеренно — он даёт двести попаданий по набору и стоит в
-- положительном случае тоже; адресата вернее брать образцом `id.task`.
переадресован AS (
  SELECT r.task_id, r.ord, r.check_id, r.text
    FROM task_ready_item r
   WHERE r.project_id = $1
     AND EXISTS (SELECT 1 FROM scheme($1) w
                  WHERE w.role = 'word.elsewhere'
                    AND lower(r.text) LIKE '%' || lower(w.value) || '%')),
-- Адресат — ПЕРВОЕ имя задачи в пункте, а не всякое.
--
-- Пункт называет и посторонние задачи: «закрывает `M5-T28` (кадр строит
-- `M5-T1`, страницу `36` с диффом — `M5-T28`)». Беря всякое имя, правило
-- завело находку про `M5-T1` — задачу, помянутую в скобке пояснением. Замер
-- 21.09: одна находка из двух была такой.
--
-- Первое — потому что адресата набор ставит сразу за отказом, и так во всех
-- пяти случаях, какие в наборе есть. Глагол («закрывает», «строит»,
-- «перечисляет») в признак не берётся: он даёт двести попаданий по набору и
-- стоит в положительном случае тоже.
--
-- ПОТОЛОК: пункт, у которого адресат назван не первым, будет прочитан
-- неверно. Такого в наборе нет ни одного, и находка о посторонней задаче
-- видна сразу — она называет имя, которого в отказе не было.
--
-- Пункт собирается из перенесённых строк проекцией: построчный счёт объявил
-- бы безадресными десять пунктов из тридцати девяти.
-- Пункт, переадресованный БЕЗ адресата, сюда не попадает вовсе.
--
-- `regexp_match` отдаёт NULL, когда имени в пункте нет, и строка-находка,
-- склеенная с NULL, вся становится NULL — гейт показывал пустые строки вместо
-- находок. Прежний `regexp_matches … 'g'` строки просто не давал, и при
-- переходе на «первого адресата» это различие я потерял.
--
-- Отбор здесь, а не в ветках: пункт без адресата не судится ни одной из них,
-- и потолок этот назван ниже.
-- АДРЕСАТОВ БЕРЁТСЯ ВСЕ, А ДОЛГ СПРАШИВАЕТСЯ, КОГДА ЗАКРЫТ ПОСЛЕДНИЙ.
--
-- Пункт переадресует не всегда в одно место: «первую половину закрывает
-- `M3-T12`, вторую — `M5-T25`». Прежде бралось ПЕРВОЕ имя, и правило
-- останавливалось на закрытой `M3-T12`, не увидев, что вторая половина ещё
-- едет в открытую `M5-T25`. Замер 21.09: из четырёх находок этой ветки ДВЕ
-- были такими — долг числился за тем, кто его уже передал.
--
-- Правило теперь простое: пока хоть один названный адресат ОТКРЫТ, долг не
-- просрочен — он у него. Закрылись все, а предмет не доказан — вот это долг.
--
-- ЧЕМ ЭТО ОПАСНО И ПОЧЕМУ ВСЁ РАВНО ВЕРНО. Прежний довод брал первое имя
-- затем, чтобы не считать адресатом задачу, помянутую в скобке пояснением, —
-- и тогда лишнее имя давало ЛОЖНУЮ НАХОДКУ. Теперь лишнее имя ОТКРЫТОЙ
-- задачи дало бы ложное молчание, а это хуже: находка видна, молчание нет.
-- Мерил на всех переадресованных пунктах набора: молчание появилось ровно на
-- тех двух, где вторая задача названа адресатом по существу, и ни на одном
-- другом.
адресат AS (
  SELECT п.task_id, п.ord, п.check_id, п.text,
         (regexp_matches(п.text,
            '(?:^|[^A-Za-z0-9_-])('
            || (SELECT string_agg(regexp_replace(value, '^\^|\$$', '', 'g'), '|')
                  FROM scheme($1) WHERE role = 'id.task')
            || ')(?![A-Za-z0-9_-])', 'g'))[1] AS кому
    FROM переадресован п),
-- ЗАЯВЛЕНИЕ, ПРЕДЪЯВИВШЕЕ ВЕРДИКТ. Только вид `checks-green`, и это граница, а
-- не выборка по вкусу.
--
-- Род `query` — свободный SQL от набора — для пунктов приёмки отозван.
-- Подсадка рядом с ним доказывала согласованность пары «запрос плюс
-- подсадка» и никогда — относимость к пункту: запрос, ложный в сессии замера
-- и истинный под `SET application_name`, закрывал ЛЮБОЙ пункт навсегда, не
-- измеряя ничего. Класс дыры — «условие, ложное в сессии замера», и
-- перечислять его формы бесполезно.
--
-- `checks-green` устроен иначе: из набора приходит СПИСОК ИМЁН, предикат
-- написан в исполнителе и проходит ревью. Имя, которого в прогоне нет, даёт
-- красное наравне с упавшим — значит заявление само проверяет, что называет
-- живую проверку.
--
-- Берётся только `passed`. `unknown` — заявление, которое НЕ ПОСЧИТАЛОСЬ, и
-- закрывать им пункт значило бы повторить ровно то, что три ветки ниже и
-- осуждают: «написанная и никогда не запущенная проверка закрывала пункт так
-- же, как зелёная». Оно остаётся в честной куче «судить нечем».
-- РОД «СУДИТСЯ НАБОРОМ» СЧИТАЕТСЯ НАРАВНЕ С «ПРОВЕРКИ ЗЕЛЕНЫ», и по той же
-- причине: у обоих вердикт СЧИТАЕТ СЕРВЕР. Довод, отозвавший `command`, на него
-- не переносится — там сервер не мог посчитать вообще ничего и отвечал
-- «неизвестно» всегда, так что один вызов двери снимал бы пункт навсегда.
--
-- Заведён он под пункты, которые судятся не задачей, а набором: «`just gate`
-- зелёный целиком», «коммит несёт закрывающий трейлер». Имени проверки у них
-- нет и быть не может, и до этого рода они лежали в куче «судить нечем» —
-- обещание теряло владельца вместо того, чтобы получить адрес. Цена измерена
-- 23.09: девять таких пунктов у двух закрытых задач остановили лестницу набора
-- целиком, и снять их было нечем.
--
-- `passed` и только он — ровно как у соседнего рода: `unknown` есть заявление,
-- которое НЕ ПОСЧИТАЛОСЬ, и закрывать им пункт значило бы повторить то, что
-- три ветки ниже и осуждают.
заявление AS (
  SELECT m.owner_id AS task_id, m.ord
    FROM readiness_method m
   WHERE m.project_id = $1 AND m.owner_kind = 'task'
     AND m.method_kind IN ('checks-green', 'judged-by-gate') AND m.verdict = 'passed'),
ответ AS (
  SELECT r.check_name, bool_or(r.verdict = 'passed') AS зелена
    FROM test_run r, прогон п
   WHERE r.project_id = $1 AND NOT r.dirty AND r.at = п.at
     -- ЗЕРКАЛО ОБЯЗАНО ПАДАТЬ, И ЭТО НЕ ПОЛОМКА. Граница та же, по которой
     -- отсеивает `G3 · test-trunk-green`, — имя бинаря, а не связь через
     -- задачу. Замер 21.09: единственная находка ветки «упала на стволе»,
     -- `M2-T3 · s10_ac_1_finding_reaches_its_delta_in_three_transitions`,
     -- жила в `mirror_finding_to_delta.rs` и падала по построению.
     AND r.ran_in NOT LIKE 'mirror\_%'
   GROUP BY r.check_name)
-- ИМЯ ПРОВЕРКИ ВЫВОДИТСЯ ИЗ ДАТЧИКА, И БЕЗ НЕГО ЭТО «НЕИЗВЕСТНО».
--
-- Пункт приёмки называет проверку либо объявленным образцом `id.check`, либо
-- тем, что функция с таким именем уже написана; второе знает датчик
-- `test-name`. Датчик несвежий — значит свободно названные проверки
-- (`undo_redo_frame`) не опознаются, и «пункт не называет проверки» было бы не
-- замером, а отсутствием замера, поданным как утверждение.
SELECT 'датчик «test-name» ' || fact_gap($1, 'test-name')
       || ': чем названы проверки пунктов приёмки — неизвестно, и это не зелёное' AS detail
 WHERE NOT fact_fresh($1, 'test-name')
   AND EXISTS (SELECT 1 FROM task_ready_item WHERE project_id = $1)
UNION ALL
-- ОБЪЯВЛЕННЫЙ СПОСОБ ЗДЕСЬ НЕ СЧИТАЕТСЯ, И ЭТО РЕШЕНИЕ, А НЕ ПРОПУСК.
--
-- Пункт приёмки и правда не обязан называть тест: «пуст вывод `rg …`»,
-- «`just gate` зелён» проверяются иначе, и для этого в приборе есть
-- `readiness_method` и дверь `method-set`. Но послабление «способ объявлен —
-- пункт закрыт» было написано и отозвано в тот же день: объявление не есть
-- прохождение.
--
-- Три дыры, измеренные на живом приборе. Способ вида `command` сервер
-- выполнить не может вовсе и отвечает «неизвестно» всегда — один вызов двери
-- снимал бы пункт навсегда. Способ вида `query`, чей запрос СЕЙЧАС красен,
-- снимал бы его так же: правило спрашивало о наличии записи, а не о её
-- вердикте. И пустой `method` при `methodKind=query` проходил бы тоже — при
-- том, что сам прибор на такой пункт отвечает «у способа вида «запрос»
-- запроса нет».
--
-- Это ровно та форма, которую три ветки ниже пункт и осуждает: «написанная и
-- никогда не запущенная проверка закрывала пункт так же, как зелёная».
-- Считать способ можно будет, когда у него появится вердикт: у `query` —
-- посчитанный сервером, у `command` — поданный, как подаются прогоны тестов.
-- СТРОКА НА ЗАДАЧУ, А НЕ НА ПУНКТ, И ЭТО НЕ СОКРАЩЕНИЕ, А ДИАГНОЗ.
--
-- Пунктов без названной проверки у одной задачи бывает по десятку, и все они
-- об одном: закрытая задача оставила чек-лист, который прибору нечем судить.
-- Строкой на пункт это давало 393 находки о двадцати шести задачах — число,
-- по которому не видно ни предмета, ни объёма, и читать его никто не станет.
--
-- Счёт без знаменателя не диагноз: «393» не говорит, много это или мало, а
-- «`M1-T1` — семь пунктов из десяти» говорит сразу. Сами пункты никуда не
-- деваются: находка называет дверь, которой их видно поимённо.
SELECT t.id || ' — закрыта, а ' || count(*) || ' из ' || (
         SELECT count(*) FROM task_ready_item a
          WHERE a.project_id = t.project_id AND a.task_id = t.id)
       || ' пунктов приёмки не называют проверки и не отмечены: судить их нечем'
       || ' — `mh call ready task=' || t.id || '`'
  FROM project_plan_tasks t
  JOIN task_ready_item r ON r.project_id = t.project_id AND r.task_id = t.id
  LEFT JOIN task_state ts ON ts.project_id = t.project_id AND ts.task_id = t.id
                         AND ts.state = 'closed'
 WHERE t.project_id = $1 AND fact_fresh($1, 'test-name')
   AND t.kind = 'dev' AND t.state = 'closed' AND NOT r.done AND r.check_id = ''
   -- ЧЕРТА ПО ДАТЕ, И ТОЛЬКО У ЭТОЙ ВЕТКИ.
   --
   -- Ветка спрашивает «есть ли чем судить пункт», и ответ на неё зависит от
   -- того, по какому правилу пункт ПИСАЛИ. Правило «пункт называет состояние,
   -- а не команду» объявлено 21.09; написанное до него писалось без него.
   --
   -- Замер, ради которого черту и поставили: 395 пунктов в 56 задачах, из них
   -- 197 «команда», 147 «прочее», 51 «трейлер» и НОЛЬ с именем проверки.
   -- Закрыть целый род не снимает почти ничего — трейлеры целиком дают ноль
   -- задач до нуля, оба крупных рода вместе шесть из пятидесяти шести.
   --
   -- Соседние ветки черты НЕ несут: пункт, называющий проверку, судим при
   -- любом правиле письма, и послаблять там нечего.
   AND coalesce(nullif(ts.closed_at, 0), ts.seen_at, 9223372036854775807) >= $2
   -- Пункт, чьё заявление посчитано и прошло, судить ЕСТЬ ЧЕМ: он и судится.
   -- Не прошедшее заявление пункт отсюда не убирает — его называет ветка ниже
   -- своими словами, а не этим «не называет проверки».
   AND NOT EXISTS (SELECT 1 FROM заявление з
                    WHERE з.task_id = r.task_id AND з.ord = r.ord)
 GROUP BY t.project_id, t.id
UNION ALL
-- ЗАЯВИЛ И НЕ ПРОШЁЛ — НАХОДКА, И ЭТО ПЛАТА ЗА ПОСЛАБЛЕНИЕ ВЫШЕ.
--
-- Строка НА ЗАДАЧУ, как и ветка выше: десять не прошедших заявлений одной
-- задачи — это по-прежнему один предмет, и десять строк о нём читать никто не
-- станет. Довод тот же, что записан двумя ветками выше.
-- Роды считаются здесь ОБА, и по той же причине, что и в ветке прохождения:
-- заявление, не прошедшее замер, обязано быть названо независимо от того, чем
-- его мерили. Молчать о красном `judged-by-gate` значило бы завести способ,
-- который закрывает пункт, когда сработал, и не говорит ничего, когда нет.
SELECT t.id || ' — заявлений о пункте приёмки не прошло: ' || count(*)
       || ' — `mh call readiness kind=task id=' || t.id || '`'
  FROM project_plan_tasks t
  JOIN task_ready_item r ON r.project_id = t.project_id AND r.task_id = t.id
  JOIN readiness_method m
    ON m.project_id = t.project_id AND m.owner_kind = 'task'
   AND m.owner_id = r.task_id AND m.ord = r.ord
   AND m.method_kind IN ('checks-green', 'judged-by-gate') AND m.verdict = 'failed'
 WHERE t.project_id = $1 AND fact_fresh($1, 'test-name')
   AND t.kind = 'dev' AND t.state = 'closed' AND NOT r.done AND r.check_id = ''
 GROUP BY t.project_id, t.id
UNION ALL
SELECT t.id || ' — проверка пункта приёмки не написана: ' || r.check_id
  FROM project_plan_tasks t
  JOIN task_ready_item r ON r.project_id = t.project_id AND r.task_id = t.id
 WHERE t.project_id = $1 AND fact_fresh($1, 'test-name') AND fact_fresh($1, 'written-tc')
   AND t.kind = 'dev' AND t.state = 'closed' AND NOT r.done
   AND r.check_id <> ''
   -- «НАПИСАНА» СПРАШИВАЕТСЯ ТАМ ЖЕ, ГДЕ СПРАШИВАЕТ `G4 · closed-unwritten`.
   --
   -- Имён здесь два рода, и проверялись они одним способом. Функция находится
   -- по имени среди фактов `test-name`; СЦЕНАРИЙ `TC-…` функцией не бывает
   -- вовсе — его переводят проверки, а связь «сценарий переведён» уже сведена
   -- в `project_written_check`. Прежнее условие искало в тексте комментария
   -- подстроку `fn TC-INDEX-01(`, которой не бывает ни в одном дереве: все
   -- 24 находки про `TC-…` были о несуществующем предмете.
   AND NOT EXISTS (SELECT 1 FROM code_fact c
                    WHERE c.project_id = t.project_id
                      AND c.kind = 'test-name' AND c.name = r.check_id)
   AND NOT EXISTS (SELECT 1 FROM project_written_check w
                    WHERE w.project_id = t.project_id AND w.check_id = r.check_id)
   -- Переадресованный пункт судится своей веткой ниже, а не этой.
   AND NOT EXISTS (SELECT 1 FROM переадресован п
                    WHERE п.task_id = r.task_id AND п.ord = r.ord)
UNION ALL
-- ПЕРЕАДРЕСАЦИЯ ПРОВЕРЯЕМА, И ПРОВЕРЯЕТСЯ СТРОЖЕ ПРЕЖНЕГО.
--
-- Пункт сказал «закрывает `Y`». Значит `Y` обязана существовать, а если `Y`
-- уже закрыта — предмет обязан быть доказан: закрытая задача, которая
-- названного не взяла, и есть долг, который прежде прятался за требованием
-- невозможного.
--
-- ПОТОЛОК НАЗВАН: пункт, переадресованный БЕЗ адресата, здесь не судится.
-- Таких сегодня три, и у всех трёх довод в самой строке — «на вехе нет»,
-- «ждёт ответа владельца», «предмет — треть сценария». Отличить довод от
-- молчания прибору нечем, и требовать адресата от всех значило бы завести
-- три находки на исправном наборе.
SELECT а.task_id || ' — пункт переадресован к ' || а.кому || ', а такой задачи в наборе нет: '
       || left(а.text, 160)
  FROM адресат а
 WHERE NOT EXISTS (SELECT 1 FROM project_plan_tasks x
                    WHERE x.project_id = $1 AND lower(x.id) = lower(а.кому))
UNION ALL
-- ОДИН ДОЛГ, НАЗВАННЫЙ ОДИН РАЗ. Строка собиралась на каждый переадресованный
-- пункт, а долг у них общий — сценарий, который никто не доказал. `M5-T5`
-- давала пять одинаковых строк подряд, и читались они как пять долгов: ни
-- адресата, ни номера пункта в тексте не было, отличить их друг от друга было
-- нечем. Счёт без своего знаменателя — не диагноз: пять пунктов, ждущих одного
-- сценария, и пять несделанных дел выглядели одинаково.
SELECT а.task_id || ' — ' || count(*) || ' пунктов переадресовано (' || string_agg(DISTINCT а.кому, ', ')
       || '), все адресаты закрыты, а ' || а.check_id || ' так и не доказан'
  FROM адресат а
 WHERE fact_fresh($1, 'written-tc') AND а.check_id <> ''
   -- Хоть один адресат ОТКРЫТ — долг у него, и он не просрочен.
   AND NOT EXISTS (SELECT 1 FROM адресат б
                     JOIN project_plan_tasks o
                       ON o.project_id = $1 AND lower(o.id) = lower(б.кому) AND o.state <> 'closed'
                    WHERE б.task_id = а.task_id AND б.ord = а.ord)
   AND EXISTS (SELECT 1 FROM project_plan_tasks y
                WHERE y.project_id = $1 AND lower(y.id) = lower(а.кому) AND y.state = 'closed')
   AND NOT EXISTS (SELECT 1 FROM project_written_check w
                    WHERE w.project_id = $1 AND w.check_id = а.check_id)
   AND NOT EXISTS (SELECT 1 FROM code_fact c
                    WHERE c.project_id = $1 AND c.kind = 'test-name' AND c.name = а.check_id)
 GROUP BY а.task_id, а.check_id
UNION ALL
-- ПРОВЕРКА НАПИСАНА — ЕЩЁ НЕ ЗНАЧИТ «ПРОШЛА».
--
-- Прежде пункт приёмки считался закрытым, если проверка с таким именем
-- нашлась в коде. Написанная и никогда не запущенная проверка закрывала пункт
-- ровно так же, как зелёная, и «готово» держалось на существовании функции.
-- Прогон у харнеса теперь свой (`test_run`, заявка 20), и вердикт берётся у
-- него: у последнего прогона с ЧИСТОГО дерева.
SELECT t.id || ' — проверка пункта приёмки упала на стволе: ' || r.check_id
  FROM project_plan_tasks t
  JOIN task_ready_item r ON r.project_id = t.project_id AND r.task_id = t.id
  JOIN ответ о ON о.check_name = r.check_id
 WHERE t.project_id = $1 AND t.kind = 'dev' AND t.state = 'closed' AND NOT r.done
   AND r.check_id <> '' AND NOT о.зелена
   -- Зеркала в `ответ` не входят вовсе — см. довод там.
UNION ALL
-- Прогона нет вовсе — это «неизвестно», а не «сошлось»: пункт говорит об этом
-- одной строкой, а не молчит по каждому пункту приёмки набора.
-- Условие — «пункты приёмки есть», а не «есть пункт с именем проверки».
-- Второе связывало единственную ветку, которая говорит «неизвестно», с
-- разбором имени: сломайся разбор — и ветка замолчала бы ровно тогда, когда
-- сказать было особенно нужно.
SELECT 'прогонов с чистого дерева не было: прошли ли проверки пунктов приёмки — неизвестно'
 WHERE NOT EXISTS (SELECT 1 FROM test_run WHERE project_id = $1 AND NOT dirty)
   AND EXISTS (SELECT 1 FROM task_ready_item WHERE project_id = $1)
 ORDER BY 1
