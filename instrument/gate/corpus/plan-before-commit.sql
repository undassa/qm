-- ЗАМЫСЕЛ ЗАПИСАН В ОДНОМ ИЗ ДВУХ МЕСТ, И ПРАВИЛО ЧИТАЕТ ОБА.
--
-- Пункт спрашивает «чем задачу делали, объяснимо ли». Прежде он читал только
-- `task_plan` — подачу `task-plan-push`. Но замысел до работы пишется в наборе
-- ДВАЖДЫ: планом и разбором предполёта, и оба по устройству встают ДО правки,
-- обоим время ставит сервер.
--
-- Замер 2026-09-21: 26 закрытых задач без плана, и предполёт сделан ВСЕМ
-- двадцати шести — ни одна не числится «ни разу не разбирали». То есть знание
-- не потеряно, оно лежало не там, куда смотрело правило. Это четвёртый случай
-- того же рода за сутки: один вопрос — два хранилища, читается одно.
--
-- ПОРЯДОК ЗДЕСЬ НЕ СУДИТСЯ, И ЭТО РЕШЕНИЕ ВЛАДЕЛЬЦА, А НЕ НЕДОСМОТР.
--
-- Прежняя редакция этого довода говорила обратное — «послабления здесь нет,
-- пересказ после закрытия не засчитан», — и она пережила решение, которое её
-- отменило. Цена стала видна 21.09: набор прочёл довод, увидел, что запрос
-- судит время только у предполёта, и ОТКАЗАЛСЯ писать четыре плана, считая,
-- что пройдёт через дыру. Отказ был добросовестным; неверен был довод.
--
-- Почему владелец снял порядок: время плана ставит сервер, а переотметить
-- закрытие можно только выдуманным коммитом. `V3-T19` закрыли без плана — и
-- погасить долг стало НЕЧЕМ: одна запись держала отдачу семидесяти семи задач
-- навсегда. Ровно та форма, которую прибор обязан не создавать: находка,
-- которую никакая работа не снимает.
--
-- Значит план, записанный задним числом, ЗАСЧИТЫВАЕТСЯ, и это не лазейка:
-- знание о задаче ценно само по себе, а дисциплина «скажи, как будешь делать,
-- прежде чем напишешь строку» стоит ступенью в скилле задачи, где её и место.
-- Здесь проверяется то, что проверяемо.
--
-- ПОТОЛОК, НАЗВАННЫЙ ЧЕСТНО: у предполёта условие `p.at < closed_at` ниже
-- ПОКА ОСТАЛОСЬ — то есть одна половина строже объявления. Снимать его молча
-- нельзя: это сняло бы находки без единой строки работы. Вынесено владельцу
-- отдельно.
--
-- Пустой разбор не считается: слот заведён с умолчанием `''`, и принять
-- пустую строку за объяснение значило бы закрыть пункт тем, что в нём ничего
-- не написано.
SELECT t.id || ' — закрыта, а замысла не записано: чем её делали, не объяснить' AS detail
  FROM project_plan_tasks t
  LEFT JOIN task_state ts
    ON ts.project_id = t.project_id AND ts.task_id = t.id AND ts.state = 'closed'
 WHERE t.project_id = $1 AND t.state = 'closed'
   AND coalesce(nullif(ts.closed_at, 0), ts.seen_at, 9223372036854775807) >= $2
   AND NOT EXISTS (SELECT 1 FROM task_plan x
                    WHERE x.project_id = t.project_id AND x.task_id = t.id)
   AND NOT EXISTS (SELECT 1 FROM preflight_verdict p
                    WHERE p.project_id = t.project_id AND p.task_id = t.id
                      AND btrim(p.body) <> ''
                      AND p.at < coalesce(nullif(ts.closed_at, 0), ts.seen_at,
                                          9223372036854775807))
 ORDER BY 1
