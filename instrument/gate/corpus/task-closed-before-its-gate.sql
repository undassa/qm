-- ОДИН КРАСНЫЙ ГЕЙТ — ОДНА НАХОДКА, А НЕ ПО ОДНОЙ НА КАЖДУЮ ЗАКРЫТУЮ ЗАДАЧУ.
-- Прежняя редакция печатала строку на задачу, и потому один гейт, ушедший в
-- красное, давал столько находок, сколько задач успели закрыть в поздних
-- фазах. Замерено: у `myack` 99 строк несли ДВА факта — «G0 не пройден» и
-- «в Ф3 таких задач 82, в Ф4 семнадцать». У соседнего набора одна строка,
-- дописанная в дерево задачи, дала 1 находку в G2 и 162 здесь каскадом.
--
-- Сто находок разом не разгребают, а перестают читать, и разгребать тут
-- нечего: действие у всех одно — пройти гейт. Строка называет его, фазу и
-- число, то есть ровно то, что измерено.
--
-- ФОРМУЛИРОВКА НЕ УТВЕРЖДАЕТ ПРЕЖДЕВРЕМЕННОСТИ. «Закрыта, а фаза не открыта»
-- читается как «закрыли раньше, чем было можно», а правило этого не мерило:
-- гейт мог покраснеть ПОСЛЕ закрытия, и тогда задача закрыта законно, а
-- красное — про сегодняшний день. Различить нечем: состояния гейта на момент
-- закрытия набор не хранит. Поэтому сказано измеренное — что закрыто и что
-- гейт не пройден сейчас.
SELECT 'фаза ' || tp.phase || ': закрытых задач ' || count(*)
       || ', а её открывает гейт ' || h.gate || ', и он не пройден. Первые: '
       || (SELECT string_agg(и, ' · ') FROM (SELECT unnest(array_agg(tp.task_id ORDER BY tp.task_id))
                                             LIMIT 8) AS x(и))
       || CASE WHEN count(*) > 8 THEN ' … и ещё ' || (count(*) - 8) ELSE '' END AS detail
  FROM task_phase tp
  JOIN LATERAL (SELECT p2.gate FROM phase p2
                 WHERE p2.ord < tp.phase_ord AND p2.gate <> ''
                   AND coalesce((SELECT s.computed FROM gate_state s
                                  WHERE s.project_id = tp.project_id
                                    AND s.gate = p2.gate), 'open') <> 'passed'
                 ORDER BY p2.ord LIMIT 1) h ON true
 WHERE tp.project_id = $1 AND tp.state = 'closed' AND tp.open IS FALSE
 GROUP BY tp.phase, h.gate
UNION ALL
-- ВИД БЕЗ ФАЗЫ — ТОЖЕ ОДИН ФАКТ НА ВИД. Отображение объявляется видом, а не
-- задачей: перечислять задачи поимённо значило бы звать чинить каждую там,
-- где чинится одно объявление.
SELECT 'вид «' || tp.kind || '» не отображён ни на одну фазу, а закрытых задач '
       || count(*) || ': судить о порядке нечем. Отображение объявляется в '
       || '`instrument/phases.json` доводом `taskKind`'
  FROM task_phase tp
 WHERE tp.project_id = $1 AND tp.state = 'closed' AND tp.phase IS NULL
 GROUP BY tp.kind
 ORDER BY 1
