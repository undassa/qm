-- ГРЕПП ПО ИМЕНИ ОТВЕЧАЕТ НА «ЕСТЬ ЛИ ССЫЛКА», А НЕ НА «РАБОТА СДЕЛАНА».
--
-- Пункт готовности, чей инструмент — текстовый поиск идентификатора задачи с
-- ожиданием ПУСТОГО вывода, невыполним по построению: имя задачи набор обязан
-- писать сам. Атрибуция пары в таблицах переводов и диапазон зеркального трека
-- в шапке модуля — оба требования набора, и оба оставляют имя в коде навсегда.
-- Одно правило обязывает имя написать, другое — не найти; меняется то из них,
-- которое меряет не свой предмет.
--
-- ЗАМЕР 22.09 (заявка 246). В tot-ade 1149 пунктов готовности, 165 держат
-- грепп, и 69 ищут им имя задачи. У девяти шаблон состоит из одних имён
-- (`V4-T7|M4-T7`) — такой пункт не меряет ничего вовсе. У шестидесяти имя
-- стоит лишней альтернативой рядом с признаками, которые предмет как раз
-- меряют («Заглушка», «Красная фаза», `just red`, имена `mirror_*`), и тогда
-- правка — выкинуть из шаблона имя. В myack таких пунктов ноль при восьми
-- греппах: там ищут `sqlx::query(`, `pg_notify`, `fn looks_structural`,
-- `todo!("TC-…")` — то есть признак предмета, а не имя того, кто его делал.
-- Ноль измерен теми же образцами имён (`M0-T11a` разбирается ими же) — это
-- отсутствие класса, а не промах ключа.
--
-- ПОВОД ЖИТЬ ПУНКТОМ, А НЕ РАЗОВОЙ ПРАВКОЙ: класс воспроизводится. Заявка 246
-- называет третий случай за смену, а найденные стоят по всем семи вехам. Пока
-- шаблон дёшево писать именем, его будут писать именем снова.
--
-- ЧИТАЮТСЯ ВСЕ ГРЕППЫ ПУНКТА, А НЕ ПЕРВЫЙ. Первая редакция правила брала один
-- шаблон на пункт и насчитала 61 вместо 69: у пяти пунктов имя стоит во втором
-- греппе. Двойные кавычки разбираются наравне с одинарными — так пишет myack.
WITH шаблоны AS (
  SELECT r.task_id,
         r.ord,
         coalesce(м[1], м[2]) AS шаблон
    FROM task_ready_item r,
         LATERAL regexp_matches(
           r.text,
           '(?:rg|grep)[^\n]*?(?:''([^'']*)''|"([^"]*)")',
           'g') AS м
   WHERE r.project_id = $1),
имена AS (
  SELECT task_id,
         ord,
         string_agg(DISTINCT шаблон, '», «' ORDER BY шаблон) AS шаблон
    FROM шаблоны
   WHERE шаблон ~ '[MV][0-9]+-T[0-9]+'
   GROUP BY task_id, ord)
SELECT task_id
       || ' · пункт готовности '
       || ord
       || ' ищет греппом имя задачи («'
       || шаблон
       || '»): имя набор пишет сам — атрибуция пары в таблицах переводов, диапазон трека в шапке модуля, — и пустым этот вывод не бывает. Инструмент пункта меряет предмет: признаки стуба в том файле, где они были бы'
  FROM имена
 ORDER BY 1
