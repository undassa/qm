-- СУДИТЬ МОЖНО ЛИШЬ ТО, ЧТО ХАРНЕС МОГ ВИДЕТЬ.
--
-- Правило требует прогона, в котором проверка падала. Прогоны харнес ведёт
-- сам (`test_run`, заявка 20), и ведёт их с недавнего времени: красная задача,
-- закрытая ДО первого записанного прогона, падающей быть не могла — не потому
-- что не падала, а потому что смотреть было некому. Требовать такого
-- доказательства значит требовать невозможного, и невозможное не чинится
-- работой: замер 21.09 держал 201 находку, ни одна не снималась ничем.
--
-- Граница названа фактом, а не послаблением: первый записанный прогон. Всё,
-- что закрыто после него, судится полностью.
-- Первый прогон и окно ниже — из партий, которые что-то измерили
-- (`test_run_measured`): прогон, упавший на сборке, ничего не видел, и ни
-- границей наблюдения, ни наблюдением в окне быть не может (заявка 103).
WITH первый AS (SELECT min(at) AS at FROM test_run_measured WHERE project_id = $1)
SELECT t.id || ' — не наблюдалась красной: ' || c.check_id AS detail
  FROM project_plan_tasks t
  JOIN project_task_check c ON c.project_id = t.project_id AND c.task_id = t.id
  JOIN task_state ts ON ts.project_id = t.project_id AND ts.task_id = t.id AND ts.state = 'closed'
  CROSS JOIN первый п
 WHERE t.project_id = $1 AND t.kind = 'red' AND t.state = 'closed'
   AND п.at IS NOT NULL
   AND coalesce(nullif(ts.closed_at, 0), ts.seen_at, 0) >= п.at
   -- СЦЕНАРИЙ НЕ БЫВАЕТ ИМЕНЕМ ПРОГОНА.
   --
   -- Колонка держит два рода имён: имя функции — оно и стоит в прогоне — и имя
   -- СЦЕНАРИЯ `TC-…`, которого в прогоне не бывает никогда: сценарий переводят
   -- проверки, и падают они под своими именами. Из двухсот показанных находок
   -- сто одна была про сценарий, то есть про предмет, которого прогон назвать
   -- не может ни при какой работе набора. Красную фазу сценария доказывают
   -- проверки той же задачи, и они здесь же и судятся.
   AND NOT EXISTS (SELECT 1 FROM project_checks pc
                    WHERE pc.project_id = $1 AND pc.id = c.check_id)
   -- ПАДЕНИЕ СЧИТАЕТСЯ ТОЛЬКО С ЧИСТОГО ДЕРЕВА. Прогон на дереве с чужой
   -- правкой роняет что угодно, и такое падение доказывало бы красную фазу
   -- чужой поломкой, а не тем, что проверка была написана до кода.
   --
   -- ПАДЕНИЕ БЕРЁТСЯ С ЛЮБОЙ ПЛАТФОРМЫ — `test_run`, а не `test_run_trunk`.
   -- Проверка под `#![cfg(windows)]` на машине харнеса собирается пустой, и
   -- пара `V5-T135` держала этот пункт навсегда: упасть она могла только на
   -- раннере Windows. Строку оттуда пишет сам харнес, разбирая журнал
   -- объявленного задания CI на стволе (`ci-job-add`), — слов набора здесь
   -- нет. Задание с `prRed` дают и свои запросы на слияние, но лишь падения:
   -- красный коммит пары при слиянии сжатием на ствол не попадает
   -- (`worker::job_run`). Граница наблюдения выше и окно ниже — своими
   -- партиями: они спрашивают, когда смотрел прибор харнеса на стволе. Пару,
   -- закрытую одним коммитом, ствол не видит никогда, и её судит граница
   -- запросов (ниже).
   --
   -- ПОТОЛОК НАЗВАН, и он общий у обоих путей: падение здесь не привязано ко
   -- времени посадки пары. Засчитывается любое чистое падение с этим именем,
   -- когда бы оно ни случилось, — и у своего прогона, и у партии CI (её
   -- `at` — начало прогона GitHub, а не миг взятия журнала). Проверка,
   -- упавшая по другой причине задолго до зеркала, закрыла бы и его.
   AND NOT EXISTS (SELECT 1 FROM test_run r
                    WHERE r.project_id = $1 AND NOT r.dirty
                      AND r.verdict = 'failed' AND r.check_name = c.check_id)
   -- ОКНО НАБЛЮДЕНИЯ ДОЛЖНО БЫЛО СУЩЕСТВОВАТЬ.
   --
   -- Зеркало красно на стволе ровно от своей посадки до посадки тела. Прибор
   -- снимал прогон РАЗ В ЧАС, а пара садится за минуты — и если между двумя
   -- посадками прохода не случилось, падения не видел никто. Не потому что не
   -- падало, а потому что смотреть было некому.
   --
   -- Замер 21.09, обе пары: `V5-T32` влита 05:16, `M5-T32` 06:20 — прохода
   -- между ними нет; `V4-T8` влита 15:51, `M4-T8` 16:07 — проходы стояли в
   -- 15:20 и 16:16. Шесть находок, и ни одна не снималась никакой работой
   -- набора: правило требовало наблюдения, которого прибор не имел
   -- возможности сделать.
   --
   -- ЭТО НЕ ПОСЛАБЛЕНИЕ, И ВОТ ЧЕМ ОНО ОТЛИЧАЕТСЯ. Прощение действует лишь
   -- там, где окно ЗАКРЫТО И ПУСТО: тело уже село, а прохода внутри не было.
   -- Пока тело не село, зеркало красно на стволе прямо сейчас — проходы идут,
   -- и падение записывается само. Спрятаться за эту ветку, слив пару быстро,
   -- больше нельзя: с этого дня прибор заглядывает в ствол каждые пять минут,
   -- то есть окно есть всегда. Корень убран в том же решении, что и правило,
   -- и порознь их принимать не следовало.
   --
   -- ПАРА, ЗАКРЫТАЯ ОДНИМ КОММИТОМ, ПРОЩЕНИЯ ОКНОМ НЕ ПОЛУЧАЕТ. Слитая сжатием
   -- пара (`tot-ade`) закрывает зеркало и тело в одно время: окно вырождено и
   -- пусто по построению, и правило без этой оговорки прощало любую такую
   -- пару, ничего не наблюдав. Замер 07.10: `V5-T334` закрыта вместе с
   -- `M5-T334` коммитом 415534a, чистых падений её проверки ноль, находки нет.
   -- Наблюдать такую пару может только задание с `prRed` в самом запросе.
   --
   -- Граница — первая отметка взятого прогона из запроса (`ci_run_taken`,
   -- имя `ci-pr:…`, `worker::JobRun::actor`): до неё прибор запросов не
   -- видел, и пара, закрытая одним коммитом раньше, падать на глазах харнеса
   -- не могла — тот же довод, что у первой партии выше. С неё — судится
   -- полностью. Набор без единого взятого прогона из запроса держит прощение,
   -- пока не объявит `prRed`: дверь от такой находки — объявление задания.
   -- По замеру 07.10 граница прощает одну пару, `V5-T334`; `V5-T46` (тоже
   -- одним коммитом) доказана падениями и прощения не просит.
   AND NOT EXISTS (
         SELECT 1 FROM red_task rt
           JOIN project_plan_tasks pt
             ON pt.project_id = $1 AND lower(pt.id) = lower(rt.parent_task)
           JOIN task_state pts
             ON pts.project_id = $1 AND pts.task_id = pt.id AND pts.state = 'closed'
          WHERE rt.project_id = $1 AND lower(rt.id) = lower(t.id)
            AND (coalesce(nullif(ts.closed_at, 0), ts.seen_at, 0)
                   < coalesce(nullif(pts.closed_at, 0), pts.seen_at, 9223372036854775807)
                 OR coalesce(nullif(ts.closed_at, 0), ts.seen_at, 0)
                   < coalesce((SELECT min(k.at) FROM ci_run_taken k
                                WHERE k.project_id = $1 AND k.actor LIKE 'ci-pr:%'),
                              9223372036854775807))
            AND NOT EXISTS (
                  SELECT 1 FROM test_run_measured w
                   WHERE w.project_id = $1
                     AND w.at > coalesce(nullif(ts.closed_at, 0), ts.seen_at, 0)
                     AND w.at < coalesce(nullif(pts.closed_at, 0), pts.seen_at,
                                         9223372036854775807)))
 ORDER BY 1
