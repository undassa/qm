-- ПАРЫ НЕТ ВОВСЕ — И ТОГДА ПОРЯДОК СРАВНИВАТЬ НЕ С ЧЕМ.
--
-- Сосед `red-before-dev` судит ПОРЯДОК: пара есть, а закрыта позже родителя.
-- Соединение с красной задачей не даёт ему строки, когда пары нет ни одной, и
-- задача кода без красной фазы проходит его молча. Замер 22.09: у `tot-ade`
-- таких задач кода шесть из девяноста шести, у `myack` — пятьдесят восемь из
-- ста сорока двух, и `red-before-dev` не называет ни одной.
--
-- ПАРА СЧИТАЕТСЯ ПО ПЛАНУ, А НЕ ПО ОБЪЯВЛЕНИЮ КРАСНОЙ ЗАДАЧИ. Строку в плане
-- пересборка ставит, только если названная веха существует, и там же приводит
-- имя родителя (`lower(btrim(…))`). Считая по `red_task`, пункт засчитывал бы
-- парой документ с несуществующей вехой: такая задача не попадает ни в план,
-- ни в очередь, то есть написана не будет, — а пункт бы молчал. Заодно
-- приведение имени не пишется здесь в третий раз.
--
-- ИСКЛЮЧЕНИЕ ЖИВЁТ В ТЕКСТЕ ЗАДАЧИ. Решение владельца (22.09): задача, у
-- которой теста до кода нет, обязана сказать это сама — поле «Без красной
-- фазы» в её таблице, а в нём почему пары нет и чем задача проверяется.
-- Отдельной двери-послабления нет нарочно: послабление, живущее не в
-- документе, читателю задачи невидимо.
--
-- ПРИЧИНА — ПРОЗОЙ, ДОКАЗАТЕЛЬСТВО — ТАМ, ГДЕ ОНО ЖИВЁТ У ВСЕХ ЗАДАЧ. Прозу
-- пункт не разбирает: греп по значению поля ошибается в обе стороны разом —
-- «и вообще `B3` тут ни при чём» проходит как названное доказательство, а
-- честный ответ именем теста строчными буквами становится находкой. Граница
-- проходит по выразимости, и выразимое здесь — таблица «Чем доказывается»,
-- которая есть у каждой задачи и уже спроецирована связью задача⇄проверка.
-- Поэтому поле отвечает «почему», а «чем» задача называет там же, где это
-- делают задачи с парой.
--
-- Набор, у которого таких связей нет ни одной, этой веткой не судится: спросить
-- «названо ли доказательство» нечем, пока разбор проверок молчит целиком.
--
-- ЧЕРТА: СУДЯТСЯ НАЧАТЫЕ, И ЭТО ПРО РАЗРЕШИМОСТЬ, А НЕ ПРО МЯГКОСТЬ.
--
-- Задача, ещё не взятая в работу, пару завести успеет, и находка о ней назвала
-- бы долгом то, что долгом не стало. Из пятидесяти восьми задач `myack` без
-- пары сорок одна разобрана предполётом, одна записана, и ни одна не начата; а
-- шестнадцать закрыты задолго до этого правила — им пару писать уже некуда, и
-- гейт стоял бы красным у всей вехи, ничего этим не меняя.
--
-- ВРЕМЯ ЗАКРЫТИЯ БЕРЁТСЯ ТОЛЬКО ИЗ КОММИТА, и неизвестное не судится. `at` у
-- двери `task-state-push` необязателен, а `seen_at` двигается при СМЕНЕ
-- состояния — у набора, подключённого сегодня, он сегодняшний у всего хвоста.
-- Прочитав их как «закрыто сегодня», пункт покраснел бы на всём закрытом разом
-- и закрыл бы выдачу задач кода целому набору.
--
-- ПОТОЛОК, И ДЕРЖАТЬ ЕГО СЕГОДНЯ НЕКОМУ: набор, чей податель не шлёт времени
-- закрытия, выпадает из этого пункта молча, и ни одно правило прибора этого не
-- называет. Соседние правила с чертой решают тот же вопрос иначе и между собой
-- несогласно — `plan-before-commit` и `ready-items-checked` судят неизвестное
-- время, `red-observed-failing` не судит. Сведение их к одному ответу — своя
-- работа со своим замером, она записана заявкой 53.
WITH судимые AS (
  SELECT t.project_id, t.id, t.entity_kind, t.entity_name
    FROM project_plan_tasks t
    LEFT JOIN task_state ts ON ts.project_id = t.project_id AND ts.task_id = t.id
   WHERE t.project_id = $1 AND t.kind = 'dev'
     AND (EXISTS (SELECT 1 FROM task_worktree w
                   WHERE w.project_id = t.project_id AND w.task_id = t.id)
          OR (t.state = 'closed' AND nullif(ts.closed_at, 0) >= $2))
     AND NOT EXISTS (SELECT 1 FROM project_plan_tasks r
                      WHERE r.project_id = t.project_id AND r.kind = 'red'
                        AND r.parent_task_id = t.id))
SELECT с.id || ' — красной пары нет, и в задаче не записано, почему: поле'
       || ' «Без красной фазы» называет причину, а доказательство идёт'
       || ' в «Чем доказывается» — `mh call task id=' || с.id || '`' AS detail
  FROM судимые с
 WHERE NOT EXISTS (SELECT 1 FROM project_document_fields f
                    WHERE f.project_id = с.project_id AND f.entity_kind = с.entity_kind
                      AND f.entity_name = с.entity_name
                      AND f.name ILIKE 'Без красной фазы%' AND btrim(f.value) <> '')
UNION ALL
SELECT с.id || ' — красной пары нет, причина записана, а доказательства нет:'
       || ' задача не называет ни одной проверки — `mh call links-of kind=task id='
       || с.id || '`'
  FROM судимые с
 WHERE EXISTS (SELECT 1 FROM project_document_fields f
                WHERE f.project_id = с.project_id AND f.entity_kind = с.entity_kind
                  AND f.entity_name = с.entity_name
                  AND f.name ILIKE 'Без красной фазы%' AND btrim(f.value) <> '')
   AND EXISTS (SELECT 1 FROM project_task_check ч WHERE ч.project_id = $1)
   AND NOT EXISTS (SELECT 1 FROM project_task_check ч
                    WHERE ч.project_id = с.project_id AND ч.task_id = с.id)
 ORDER BY 1
