-- ПРОБА, НЕ РОНЯЮЩАЯ СВОЙ ПУНКТ, — ЭТО ПУНКТ, КОТОРЫЙ НИЧЕГО НЕ ЛОВИТ.
--
-- У каждого пункта гейта есть проба: она подсаживает в набор нарушение и
-- требует, чтобы пункт покраснел. Приговор пробы хранится (`probe_ok`) и
-- отдаётся дверью — а не читал его ни один пункт. Узнать, что проба перестала
-- ронять свой пункт, можно было только позвав самотест руками и прочитав ответ
-- глазами.
--
-- Замер 21.09: за смену прибор правился пятнадцать раз, и самотест прогнан
-- один — в конце. У набора `myack` он нашёл четыре пункта, чья проба не роняет
-- их вовсе: сущностей нужного вида в наборе нет, подсаживать не во что, и
-- замер проходит ПО ОТСУТСТВИЮ. Четыре пункта были зелены, и никто не знал,
-- поймали бы они хоть что-нибудь.
--
-- Пустой предмет считается пройденным намеренно (решение владельца), и это не
-- отменяется. Отменяется молчание об этом: пункт, который нечем проверить,
-- обязан говорить это сам, а не ждать, пока кто-то вспомнит про самотест.
--
-- `probe_ok IS NULL` — пробы нет вовсе либо самотест не звали: это «не
-- объявлено», и о нём говорит соседний пункт. Здесь судится только ложь: проба
-- есть, прогнана, и пункт на неё не отреагировал.
SELECT 'пункт ' || g.phase || ' · ' || g.id
       || ' — проба его не роняет: подсаженное нарушение он не увидел. '
       || 'Зелёный такого пункта ничего не доказывает — `mh call gate-selftest`' AS detail
  FROM project_gates g
 WHERE g.project_id = $1 AND g.probe_ok IS FALSE
 ORDER BY 1
