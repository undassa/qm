-- НЕПРИМЕНИМЫЙ ПУНКТ НАЗВАН РЕШЕНИЕМ ПРОЕКТА.
--
-- Пункт неприменим, когда проект не выполняет его требований: статьи нет в
-- реестре пар, технологии нет в стеке. И то и другое — правка документа, и без
-- этого пункта одна правка конституции молча выключала двадцать одно правило
-- G4, а гейт оставался зелёным (ревью undassa/mh#181). Прежде харнес держал
-- обратное: неприменимость — установленное отсутствие, а не решение (6950cb6),
-- и отказ от пункта (`gate_item_waiver`) был снят.
--
-- Неприменимость по требованию остаётся (решение владельца 2026-10-06), но
-- тихой она быть не может: правило, которое к проекту не относится, называет
-- решение проекта — с доводом, в ревью, в летописи. Решение называет пункт его
-- именем; совпадение имени в тексте и есть ссылка.
SELECT 'пункт ' || g.phase || ' · ' || g.id || ' неприменим ('
       || coalesce(g.result->>'why', 'причина не записана')
       || '), а решения, называющего его, в наборе нет: выключить правило — значит решить это и записать'
       AS detail
  FROM project_gates g
 WHERE g.project_id = $1 AND g.applicable IS FALSE
   AND NOT EXISTS (SELECT 1 FROM project_documents d
                    WHERE d.project_id = $1 AND d.entity_kind = 'decision'
                      AND position(g.id IN d.content) > 0)
 ORDER BY 1
